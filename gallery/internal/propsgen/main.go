// Command propsgen writes the gallery's props tables (props_gen.go) from
// the kit's Go: each component's doc comment and fields.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
	"unicode"
)

// kitFiles hold components written in Go; the rest are compiled from
// .vuka.html files (x_html.go).
var kitFiles = []string{"button.go", "dialog.go", "field.go", "present.go"}

// kitFuncs are components the kit writes as functions.
var kitFuncs = []string{"Actions", "Icon", "Spinner"}

type prop struct{ Name, Type, Default, Doc string }

type typeDoc struct {
	Doc    string
	Kit    bool
	Fields []prop
}

func main() {
	dir := ".."
	if len(os.Args) > 1 {
		dir = os.Args[1]
	}
	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, dir, func(fi os.FileInfo) bool { return !strings.HasSuffix(fi.Name(), "_test.go") }, parser.ParseComments)
	if err != nil {
		log.Fatal(err)
	}
	pkg := pkgs["ui"]
	if pkg == nil {
		log.Fatal("no package ui in ", dir)
	}
	specs := map[string]*ast.TypeSpec{}
	docs := map[string]string{}
	funcs := map[string]string{}
	kit := map[string]bool{}
	for name, f := range pkg.Files {
		base := filepath.Base(name)
		for _, d := range f.Decls {
			switch d := d.(type) {
			case *ast.GenDecl:
				for _, s := range d.Specs {
					ts, ok := s.(*ast.TypeSpec)
					if !ok || !ts.Name.IsExported() {
						continue
					}
					specs[ts.Name.Name] = ts
					doc := ts.Doc
					if doc == nil {
						doc = d.Doc
					}
					docs[ts.Name.Name] = doc.Text()
				}
			case *ast.FuncDecl:
				if d.Recv == nil && slices.Contains(kitFuncs, d.Name.Name) {
					funcs[d.Name.Name] = cleanDoc(d.Doc.Text())
				}
				if d.Recv == nil || d.Name.Name != "Render" || len(d.Recv.List) != 1 {
					continue
				}
				t := d.Recv.List[0].Type
				if ix, ok := t.(*ast.IndexExpr); ok {
					t = ix.X
				}
				id, ok := t.(*ast.Ident)
				if ok && (strings.HasSuffix(base, "_html.go") || slices.Contains(kitFiles, base)) {
					kit[id.Name] = true
				}
			}
		}
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/propsgen from the kit's Go. DO NOT EDIT.\n\npackage gallery\n\nvar typeDocs = map[string]typeDoc{\n")
	for _, name := range sorted(mapsKeys(kit)) {
		td := typeDoc{Doc: cleanDoc(docs[name]), Kit: true}
		st := structOf(specs, name)
		if st != nil {
			for _, f := range st.Fields.List {
				if f.Tag != nil && strings.Contains(f.Tag.Value, `vuka:"-"`) {
					continue
				}
				var tb bytes.Buffer
				printer.Fprint(&tb, fset, f.Type)
				doc := cleanDoc(f.Doc.Text())
				for _, n := range f.Names {
					if !n.IsExported() {
						continue
					}
					td.Fields = append(td.Fields, prop{Name: n.Name, Type: tb.String(), Default: defaultOf(tb.String(), doc), Doc: doc})
				}
			}
		}
		fmt.Fprintf(&b, "\t%q: {Doc: %q, Fields: []Prop{\n", name, td.Doc)
		for _, p := range td.Fields {
			fmt.Fprintf(&b, "\t\t{Name: %q, Attr: %q, Type: %q, Default: %q, Doc: %q},\n", p.Name, attrName(p.Name), p.Type, p.Default, p.Doc)
		}
		b.WriteString("\t}},\n")
	}
	b.WriteString("}\n\nvar funcDocs = map[string]string{\n")
	for _, name := range sorted(mapsKeys(funcs)) {
		fmt.Fprintf(&b, "\t%q: %q,\n", name, funcs[name])
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("props_gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// structOf is a type's struct, following a type defined as another
// (type Input Field).
func structOf(specs map[string]*ast.TypeSpec, name string) *ast.StructType {
	for range 3 {
		ts := specs[name]
		if ts == nil {
			return nil
		}
		switch t := ts.Type.(type) {
		case *ast.StructType:
			return t
		case *ast.Ident:
			name = t.Name
		default:
			return nil
		}
	}
	return nil
}

var lineDirective = regexp.MustCompile(`(?m)^line \S+\n?`)

func cleanDoc(s string) string {
	s = lineDirective.ReplaceAllString(s, "")
	return strings.TrimSpace(s)
}

var defaultRes = []*regexp.Regexp{
	regexp.MustCompile(`(\S+) \(default\)`),
	regexp.MustCompile(`(\S+) \(the default\)`),
	regexp.MustCompile(`[Dd]efault(?:s to| is)? ("[^"]*"|[0-9]+|[A-Z]\w+)[.;]`),
}

// defaultOf is the default a field's doc names.
func defaultOf(typ, doc string) string {
	if typ == "bool" {
		return "false"
	}
	doc = strings.Join(strings.Fields(doc), " ")
	for _, re := range defaultRes {
		if m := re.FindStringSubmatch(doc); m != nil {
			return strings.TrimRight(m[1], ".,;:)")
		}
	}
	return ""
}

// attrName is a field's attribute in markup: Variant → variant, ID → id,
// IconOnly → iconOnly.
func attrName(s string) string {
	r := []rune(s)
	i := 0
	for i < len(r) && unicode.IsUpper(r[i]) {
		i++
	}
	switch {
	case i == len(r):
		return strings.ToLower(s)
	case i > 1:
		i--
	}
	return strings.ToLower(string(r[:i])) + string(r[i:])
}

func mapsKeys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	return out
}

func sorted(s []string) []string { slices.Sort(s); return s }
