// Command cssgen keeps the public Go stylesheet constants in sync with CSS.
package main

import (
	"fmt"
	"go/format"
	"os"
)

func main() {
	out := "// Code generated by internal/cssgen from ui.css and preset-shadcn.css; DO NOT EDIT.\n\npackage ui\n\n"
	for _, item := range []struct{ file, name, doc string }{
		{"ui.css", "Styles", "Styles is the kit stylesheet. Override its --ui-* tokens to theme every component."},
		{"preset-shadcn.css", "ShadcnStyles", "ShadcnStyles is the opt-in shadcn token alias layer. Load it after Styles."},
	} {
		b, err := os.ReadFile(item.file)
		must(err)
		out += fmt.Sprintf("// %s\nconst %s = %q\n\n", item.doc, item.name, b)
	}
	b, err := format.Source([]byte(out))
	must(err)
	must(os.WriteFile("theme_css.go", b, 0644))
}

func must(err error) {
	if err != nil {
		panic(err)
	}
}
